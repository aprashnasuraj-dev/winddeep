// Bounded offline synthetic ETH66 downloader event-path fixture.
// This does not establish live peer ingress, QBFT quorum impact, or a vulnerability.
package downloader

import (
    "math/big"
    "testing"
    "time"

    "github.com/electroneum/electroneum-sc/eth/protocols/eth"
)

func TestWorkerBWithheldPeerHeadTriggersUnverifiedSyncStart(t *testing.T) {
    cases := []struct {
        name     string
        withhold bool
        inflateTD bool
    }{
        {"honest_peer_control", false, false},
        {"withheld_head_real_td", true, false},
        {"withheld_head_inflated_td", true, true},
    }
    for _, tc := range cases {
        t.Run(tc.name, func(t *testing.T) {
            tester := newTester(t)
            defer tester.terminate()

            // This exact 800/8 case is pre-generated by downloader testchain init.
            // Shortening an arbitrary length would panic after pregenerated=true.
            chain := testChainBase.shorten(800 / 8)
            peer := tester.newPeer("worker-b-synthetic-eth66", eth.ETH66, chain.blocks[1:])
            head, realTD := peer.Head()
            claimedTD := new(big.Int).Set(realTD)
            if tc.withhold {
                peer.withholdHeaders[head] = struct{}{}
                if tc.inflateTD {
                    claimedTD.SetInt64(999999999)
                }
            }

            sub := tester.downloader.mux.Subscribe(StartEvent{}, DoneEvent{}, FailedEvent{})
            defer sub.Unsubscribe()
            started := time.Now()
            initialHeight := tester.chain.CurrentBlock().NumberU64()

            // CRITICAL: TypeMux.Post waits for subscribers. Calling sync in the
            // test goroutine deadlocks at StartEvent before the first receive.
            // Consume the events while the actual synchronisation runs.
            syncResult := make(chan error, 1)
            go func() {
                syncResult <- tester.sync(peer.id, claimedTD, FullSync)
            }()

            observed := make([]string, 0, 2)
            deadline := time.NewTimer(25 * time.Second)
            defer deadline.Stop()
            for len(observed) < 2 {
                select {
                case ev, ok := <-sub.Chan():
                    if !ok || ev == nil {
                        tester.downloader.Cancel()
                        t.Fatal("downloader event subscription terminated")
                    }
                    switch ev.Data.(type) {
                    case StartEvent:
                        observed = append(observed, "START")
                    case DoneEvent:
                        observed = append(observed, "DONE")
                    case FailedEvent:
                        observed = append(observed, "FAILED")
                    }
                case <-deadline.C:
                    tester.downloader.Cancel()
                    t.Fatalf("downloader did not terminate within bounded lifecycle window: events=%v", observed)
                }
            }

            var err error
            select {
            case err = <-syncResult:
            case <-time.After(10 * time.Second):
                tester.downloader.Cancel()
                t.Fatal("download operation did not return after its terminal event")
            }
            if observed[0] != "START" {
                t.Fatalf("missing unverified downloader StartEvent: %v", observed)
            }

            failureOrCompletionMs := time.Since(started).Milliseconds()
            finalHeight := tester.chain.CurrentBlock().NumberU64()
            if tc.withhold {
                if finalHeight != initialHeight {
                    t.Fatalf("withheld-header peer unexpectedly advanced canonical height: initial=%d final=%d", initialHeight, finalHeight)
                }
                t.Logf("B_WITHHELD_HEAD_NO_CANONICAL_PROGRESS case=%s height=%d", tc.name, finalHeight)
                if err == nil || observed[1] != "FAILED" {
                    t.Fatalf("withholding peer unexpectedly admitted: err=%v events=%v", err, observed)
                }
                t.Logf("B_WITHHELD_HEAD_TRIGGERED_START_BEFORE_FAILURE case=%s inflated_td=%t duration_ms=%d err=%v",
                    tc.name, tc.inflateTD, time.Since(started).Milliseconds(), err)
                // Recovery counterexample: after the malicious peer fails, a new
                // honest peer must still permit this downloader to advance.
                // This is a local downloader recovery oracle, not QBFT finality.
                recoveryStarted := time.Now()
                recoveryPeer := tester.newPeer("worker-b-recovery-peer", eth.ETH66, chain.blocks[1:])
                recoveryHead, recoveryTD := recoveryPeer.Head()
                recoveryResult := make(chan error, 1)
                go func() {
                    recoveryResult <- tester.sync(recoveryPeer.id, recoveryTD, FullSync)
                }()
                recoveryEvents := make([]string, 0, 2)
                recoveryDeadline := time.NewTimer(25 * time.Second)
                defer recoveryDeadline.Stop()
                for len(recoveryEvents) < 2 {
                    select {
                    case ev, ok := <-sub.Chan():
                        if !ok || ev == nil {
                            tester.downloader.Cancel()
                            t.Fatal("recovery event subscription terminated")
                        }
                        switch ev.Data.(type) {
                        case StartEvent:
                            recoveryEvents = append(recoveryEvents, "START")
                        case DoneEvent:
                            recoveryEvents = append(recoveryEvents, "DONE")
                        case FailedEvent:
                            recoveryEvents = append(recoveryEvents, "FAILED")
                        }
                    case <-recoveryDeadline.C:
                        tester.downloader.Cancel()
                        t.Fatalf("recovery did not complete: events=%v", recoveryEvents)
                    }
                }
                var recoveryErr error
                select {
                case recoveryErr = <-recoveryResult:
                case <-time.After(10 * time.Second):
                    tester.downloader.Cancel()
                    t.Fatal("recovery sync did not return")
                }
                recoveredHeight := tester.chain.CurrentBlock().NumberU64()
                if recoveryErr != nil || recoveryEvents[0] != "START" || recoveryEvents[1] != "DONE" || recoveredHeight <= finalHeight {
                    t.Fatalf("honest recovery failed: err=%v events=%v height=%d previous=%d", recoveryErr, recoveryEvents, recoveredHeight, finalHeight)
                }
                if tester.chain.CurrentBlock().Hash() != recoveryHead {
                    t.Fatalf("recovery completed at non-peer canonical head: local=%s peer=%s height=%d", tester.chain.CurrentBlock().Hash(), recoveryHead, recoveredHeight)
                }
                t.Logf("B_WITHHELD_HEAD_RECOVERY_HEAD_MATCH case=%s head=%s", tc.name, recoveryHead)
                t.Logf("B_WITHHELD_HEAD_HONEST_RECOVERY case=%s from=%d to=%d failure_ms=%d recovery_ms=%d", tc.name, finalHeight, recoveredHeight, failureOrCompletionMs, time.Since(recoveryStarted).Milliseconds())
            } else {
                if finalHeight <= initialHeight {
                    t.Fatalf("honest peer completed without canonical height progress: initial=%d final=%d", initialHeight, finalHeight)
                }
                if tester.chain.CurrentBlock().Hash() != head {
                    t.Fatalf("honest sync completed at non-peer canonical head: local=%s peer=%s", tester.chain.CurrentBlock().Hash(), head)
                }
                t.Logf("B_HONEST_PEER_HEAD_MATCH head=%s", head)
                t.Logf("B_HONEST_PEER_CANONICAL_PROGRESS initial=%d final=%d", initialHeight, finalHeight)
                if err != nil || observed[1] != "DONE" {
                    t.Fatalf("honest peer failed: err=%v events=%v", err, observed)
                }
                t.Logf("B_HONEST_PEER_COMPLETED_SYNC duration_ms=%d", failureOrCompletionMs)
            }
        })
    }
}
