// Bounded offline synthetic ETH66 downloader event-path fixture.
// This does not establish live peer ingress, QBFT quorum impact, or a vulnerability.
package downloader

import (
    "math/big"
    "testing"
    "time"

    "github.com/electroneum/electroneum-sc/eth/protocols/eth"
)

func TestWorkerBWithheldPeerHeadTriggersUnverifiedSyncStart(t *testing.T) {
    cases := []struct {
        name     string
        withhold bool
    }{
        {"honest_peer_control", false},
        {"nonserving_head_peer", true},
    }
    for _, tc := range cases {
        t.Run(tc.name, func(t *testing.T) {
            tester := newTester(t)
            defer tester.terminate()

            // This exact 800/8 case is pre-generated by downloader testchain init.
            // Shortening an arbitrary length would panic after pregenerated=true.
            chain := testChainBase.shorten(800 / 8)
            peer := tester.newPeer("worker-b-synthetic-eth66", eth.ETH66, chain.blocks[1:])
            head, realTD := peer.Head()
            claimedTD := new(big.Int).Set(realTD)
            if tc.withhold {
                peer.withholdHeaders[head] = struct{}{}
                claimedTD.SetInt64(999999999)
            }

            sub := tester.downloader.mux.Subscribe(StartEvent{}, DoneEvent{}, FailedEvent{})
            defer sub.Unsubscribe()
            started := time.Now()

            // CRITICAL: TypeMux.Post waits for subscribers. Calling sync in the
            // test goroutine deadlocks at StartEvent before the first receive.
            // Consume the events while the actual synchronisation runs.
            syncResult := make(chan error, 1)
            go func() {
                syncResult <- tester.sync(peer.id, claimedTD, FullSync)
            }()

            observed := make([]string, 0, 2)
            deadline := time.NewTimer(25 * time.Second)
            defer deadline.Stop()
            for len(observed) < 2 {
                select {
                case ev, ok := <-sub.Chan():
                    if !ok || ev == nil {
                        tester.downloader.Cancel()
                        t.Fatal("downloader event subscription terminated")
                    }
                    switch ev.Data.(type) {
                    case StartEvent:
                        observed = append(observed, "START")
                    case DoneEvent:
                        observed = append(observed, "DONE")
                    case FailedEvent:
                        observed = append(observed, "FAILED")
                    }
                case <-deadline.C:
                    tester.downloader.Cancel()
                    t.Fatalf("downloader did not terminate within bounded lifecycle window: events=%v", observed)
                }
            }

            var err error
            select {
            case err = <-syncResult:
            case <-time.After(10 * time.Second):
                tester.downloader.Cancel()
                t.Fatal("download operation did not return after its terminal event")
            }
            if observed[0] != "START" {
                t.Fatalf("missing unverified downloader StartEvent: %v", observed)
            }

            if tc.withhold {
                if err == nil || observed[1] != "FAILED" {
                    t.Fatalf("withholding peer unexpectedly admitted: err=%v events=%v", err, observed)
                }
                t.Logf("B_WITHHELD_HEAD_TRIGGERED_START_BEFORE_FAILURE duration_ms=%d err=%v",
                    time.Since(started).Milliseconds(), err)
            } else {
                if err != nil || observed[1] != "DONE" {
                    t.Fatalf("honest peer failed: err=%v events=%v", err, observed)
                }
                t.Log("B_HONEST_PEER_COMPLETED_SYNC")
            }
        })
    }
}
